private fun LazyListScope.section(title: String, content: String) {
    item {
        Column(
            modifier = Modifier.fillMaxWidth().padding(top = 8.dp),
            verticalArrangement = Arrangement.spacedBy(4.dp)
        ) {
            Text(title, style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
            Text(content, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
    }
}

private fun LazyListScope.lesson(title: String, content: String) {
    item(key = title, contentType = "lesson") { LessonCard(title, content) }
}

@Composable
private fun LessonCard(title: String, content: String) {
    Card(modifier = Modifier.fillMaxWidth()) {
        Column(Modifier.padding(18.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
            Text(title, style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.SemiBold)
            Text(content, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
    }
}

/** Bound text layout work per lazy item without discarding any document content. */
private fun LazyListScope.documentParagraphs(content: String) {
    content.lineSequence().filter { it.isNotBlank() }.forEach { paragraph ->
        paragraph.chunked(600).forEach { chunk ->
            item(contentType = "document_text") {
                Text(chunk, style = MaterialTheme.typography.bodyLarge)
            }
        }
    }
}
