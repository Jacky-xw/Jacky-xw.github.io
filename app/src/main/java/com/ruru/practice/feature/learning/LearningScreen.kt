@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun LearningScreen() {
    val context = LocalContext.current
    val pagerState = rememberPagerState(pageCount = { learningTabs.size })
    val scope = rememberCoroutineScope()

    // 资源只作为普通文本读取，不参与缓存、阅读位置或折叠状态。
    val yinfuTexts = remember(context) { LearningTextCache.yinfuTexts(context) }
    val bodhisattvaTexts = remember(context) { LearningTextCache.bodhisattvaTexts(context) }

    Surface(modifier = Modifier.fillMaxSize()) {
        Column(modifier = Modifier.fillMaxSize()) {
            ScrollableTabRow(
                selectedTabIndex = pagerState.currentPage,
                edgePadding = 8.dp,
                modifier = Modifier.fillMaxWidth()
            ) {
                learningTabs.forEachIndexed { index, title ->
                    Tab(
                        selected = pagerState.currentPage == index,
                        onClick = { scope.launch { pagerState.animateScrollToPage(index) } },
                        text = { Text(title) }
                    )
                }
            }
            HorizontalPager(
                state = pagerState,
                modifier = Modifier.weight(1f).fillMaxWidth(),
                beyondViewportPageCount = 1
            ) { page ->
                LazyColumn(
                    modifier = Modifier.fillMaxSize().padding(horizontal = 20.dp),
                    contentPadding = PaddingValues(top = 12.dp, bottom = 24.dp),
                    verticalArrangement = Arrangement.spacedBy(12.dp)
                ) {
                    item {
                        Text("学习中心", style = MaterialTheme.typography.headlineMedium, fontWeight = FontWeight.Bold)
                        Text(
                            "把教法放回经验中理解，再用修习检验。左右滑动可切换分类。",
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                    when (page) {
                        0 -> ancientYinfuPath(yinfuTexts)
                        1 -> bodhisattvaPath(bodhisattvaTexts)
                        2 -> mainPath()
                        3 -> householdEightfoldPath()
                        4 -> anapanasati()
                        5 -> hindrances()
                        6 -> walkingMeditation()
                        7 -> senseRestraint()
                        8 -> aggregatesPractice()
                        9 -> dependentOriginationPractice()
                        10 -> longTerm()
                        11 -> glossary()
                        else -> safety()
                    }
                }
            }
        }
    }
}

private fun readRawTextSafely(context: Context, @RawRes resourceId: Int): String =
    runCatching {
        context.resources.openRawResource(resourceId).bufferedReader(Charsets.UTF_8).use { it.readText() }
    }.getOrElse { error ->
        "文本读取失败：${error.message ?: error.javaClass.simpleName}"
    }

private fun LazyListScope.ancientYinfuPath(contents: List<String>) {
    yinfuDocument(
        title = "《古阴符经》的真相·上篇",
        content = contents.getOrElse(0) { "" },
        imageIds = listOf(R.drawable.guyinfujing_image_1, R.drawable.guyinfujing_image_2)
    )
    yinfuDocument(
        title = "《古阴符经》的真相·下篇",
        content = contents.getOrElse(1) { "" },
        imageIds = listOf(R.drawable.guyinfujing_image_3)
    )
}

/** The three NUL positions in the source texts are the original inline-image anchors. */
private fun LazyListScope.yinfuDocument(title: String, content: String, imageIds: List<Int>) {
    val parts = content.split('\u0000')
    item {
        Text(title, style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.SemiBold)
    }
    parts.forEachIndexed { index, part ->
        if (part.isNotBlank()) {
            documentParagraphs(part)
        }
        imageIds.getOrNull(index)?.let { imageId ->
            item {
                Card(modifier = Modifier.fillMaxWidth()) {
                    Image(
                        painter = painterResource(imageId),
                        contentDescription = "$title 配图 ${index + 1}",
                        modifier = Modifier.fillMaxWidth().padding(8.dp),
                        contentScale = ContentScale.FillWidth
                    )
                }
            }
        }
    }
}

